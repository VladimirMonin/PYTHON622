// Методы массивов в JS
// push() - добавляет элемент в конец массива
// unshift() - добавляет элемент в начало массива
// pop() - удаляет последний элемент массива и возвращает его
// shift() - удаляет первый элемент массива и возвращает его

// length - свойство, возвращающее количество элементов в массиве

// split() - метод, который разделяет строку на массив подстрок, используя указанный разделитель
// join() - метод, который объединяет все элементы массива в строку, используя указанный разделитель

// indexOf() - метод, который возвращает индекс первого вхождения указанного элемента в массиве, или -1, если элемент не найден
// includes() - метод, который проверяет, содержит ли массив определенный элемент, возвращая true или false
// slice() - метод, который возвращает новый массив, содержащий копию части исходного массива, определенной начальным и конечным индексами
// splice() - метод, который изменяет содержимое массива, удаляя существующие элементы и/или добавляя новые элементы

// forEach() - метод, который выполняет указанную функцию один раз для каждого элемента массива
// map() - метод, который создает новый массив с результатом вызова указанной функции для каждого элемента массива
// filter() - метод, который создает новый массив со всеми элементами, прошедшими проверку, задаваемую в передаваемой функции
// reduce() - метод, который применяет функцию к аккумулятору и каждому элементу массива (слева направо), сводя его к одному значению
// sort() - метод, который сортирует элементы массива на месте и возвращает отсортированный массив
// reverse() - метод, который изменяет порядок элементов массива на обратный и возвращает массив

