// Slice и Splice работают как на строках так и на массивах с индексами.
// Slice(start, end) - возвращает новый массив, содержащий элементы от start до end (не включая end)
// Splice(start, deleteCount, item1, item2, ...) - изменяет массив, удаляя deleteCount элементов, начиная с start, и вставляя item1, item2 и т.д. на их место

// может удалить элементы
// может вставить элементы
// может заменить элементы
// всегда возвращает массив удаленных элементов
// исходный массив при этом меняется
// array.splice(start, deleteCount, item1, item2, ...)

// Обязательные и необязательные параметры

// start - обязательный по смыслу параметр.
// С какого индекса начать работу.
// Если индекс отрицательный, отсчет идет с конца массива.
// deleteCount - не всегда обязателен, но обычно нужен.
// Сколько элементов удалить, начиная с start.
// Если поставить 0, удаление не произойдет.
// item1, item2, ... - необязательные.
// Какие элементы вставить на место удаленных.
// Можно не передавать ничего, тогда будет только удаление.
// Можно передать один элемент или несколько.
// Что важно запомнить

// splice изменяет исходный массив
// splice не делает копию
// splice возвращает удаленные элементы
// если ничего не удаляли, вернется пустой массив

// Мини-шпаргалка

// удалить 1 элемент: splice(index, 1)
// удалить несколько: splice(index, count)
// вставить без удаления: splice(index, 0, item)
// заменить элемент: splice(index, 1, item)
// вставить несколько: splice(index, 0, item1, item2)

