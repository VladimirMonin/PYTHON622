"""
Методы `keys`, `items` и `values` позволяют получить из конкретного словаря структуру, похожую на список. Эта структура — служебный тип данных, который содержит ключи, значения и пары "ключ-значение". Это очень удобно для перебора этих данных в цикле.

В цикле `for` вы можете итерироваться по ключам, по значениям и по парам ключ/значение одновременно. Когда вы будете итерироваться по `items` (которые представляют собой пару "ключ-значение"), фактически вы будете перебирать структуру, похожую на список списков.

Для этого используется технология распаковки списка: вложенный список, представляющий собой ключ и значение, распаковывается на две переменные. Данные, содержащие информацию по ключу, ложатся в первую переменную, а данные из значения — во вторую.

"""

"""
`Кортеж` или `Tuple` в Python — это неизменяемая упорядоченная коллекция элементов. Поскольку коллекция неизменяема, у него нет особых методов: вы не можете добавлять элементы, удалять их или изменять по индексу.

С `Кортеж` можно только создать его и обойти циклом или получить элементы по индексу. Обычно он используется служебными функциями Python. Кроме того, вы можете использовать его для фиксации важной информации, которая не должна меняться (например, количество дней недели или месяцев в году).

Также никогда не стоит объявлять переменную, записывая `число, число = ...`, потому что в таком случае вы не создадите дробное число (`float`).

При создании `Кортеж` из двух элементов помните: все дробные числа в Python пишутся через точку.
"""

