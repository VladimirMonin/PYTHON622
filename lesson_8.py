name_tuple = ("name", "Филлип")
key, value = name_tuple

"""
Символ нижнего подчеркивания в `Python` используется как техническая переменная; в английском языке она называется `wildcard`.

Она создается для случая, когда вам нужна временная переменная — чтобы временно положить данные туда, которые вы никогда дальше не будете использовать.
"""
key, *_ = name_tuple
print(key)  # 'name'
print(_)  # ['Филлип']

