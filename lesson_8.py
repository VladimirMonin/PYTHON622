# Словари в Пайтон

"""
Словари в Python — это формат данных, где вы используете ключ и значение. Ключом словаря может быть любой элемент множества. Они являются достаточно близкими родственниками структур данных `set`.

Это означает несколько ключевых свойств:
1.  **Хеширование:** Ключи словаря хэшируются. Если вы знаете ключ, данные можно получить очень быстро.
2.  **Уникальность:** Ключи не могут быть дубликатами. В словаре нельзя иметь два одинаковых ключа.
3.  **Иммутабельность:** Ключами могут быть только неизменяемые типы данных (immutable types).

Из этих типов данных наиболее популярными, которые служат ключами словарей, являются числа и строки. Из менее редких случаев — булевы значения (`bool`), `NaN` и кортежи (`tuple`).
"""

